/** 打乱顶层键插入顺序（内容不变），用于验证 stableStringify 的键序无关性。 */
export function shuffledCopy(chart: ChartResult): ChartResult {
  const entries = Object.entries(chart).reverse();
  return Object.fromEntries(entries) as ChartResult;
}

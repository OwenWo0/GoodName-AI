/**
 * 从自由文本提取汉字列表（去重、保序、上限 30）——用于避讳字/禁用字输入。
 */
export function splitHanChars(text: string): string[] {
  const matched = text.match(/[一-鿿]/g) ?? [];
  return Array.from(new Set(matched)).slice(0, 30);
}


/**
 * 格局门单测（喜用神算法修复 C.1）：从格五条件 / 假从降级 / 专旺纯粹性与破格 / 时辰未知口径。
 * 判别重点：
 * - 根=本气+中气（同我∪生我）——弱水盘戌中辛（中气生我）即有根，**不得**误判从格；
 * - 仅余气微根（壬辰盘）→ 假从按正格论；
 * - 破格（申中庚官杀破曲直）→ 静默 null 不留噪音；
 * - 时辰未知：真从降假、专旺不判+争议。
 */
import { describe, expect, it } from 'vitest';
import { detectGeju, 从格喜忌表 } from '@/lib/xiyong/geju';
import { 构造八字, 构造四柱, 缺时柱, 锚点 } from './fixtures';

const scan = (b: ReturnType<typeof 构造八字>) => detectGeju(b.日主, b.四柱);

describe('从格喜忌钉表', () => {
  it('四类喜忌与任务书一致（类别口径，勿推导）', () => {
    expect(从格喜忌表['从财']).toEqual({ 喜: ['食伤', '财星'], 忌: ['印星', '比劫'] });
    expect(从格喜忌表['从杀']).toEqual({ 喜: ['财星', '官杀'], 忌: ['印星', '比劫', '食伤'] });
    expect(从格喜忌表['从儿']).toEqual({ 喜: ['食伤', '财星'], 忌: ['印星', '比劫'] });
    expect(从格喜忌表['从势']).toEqual({ 喜: ['食伤', '财星', '官杀'], 忌: ['印星', '比劫'] });
  });
});

describe('从格', () => {
  it('F1 壬水全盘木火：真从财，喜[食伤,财星]忌[印星,比劫]，调候不得劫持（胜出在调用方钉）', () => {
    const { 格局 } = scan(锚点['F1从财']());
    expect(格局).not.toBeNull();
    expect(格局!.类型).toBe('从格');
    expect(格局!.名称).toBe('从财格');
    expect(格局!.真伪).toBe('真');
    expect(格局!.喜类别).toEqual(['食伤', '财星']);
    expect(格局!.忌类别).toEqual(['印星', '比劫']);
    expect(格局!.中性类别).toEqual([]);
  });

  it('壬辰盘：辰余气癸微根 → 假从（真伪=假 + 争议标注，喜忌表仍钉死供展示）', () => {
    const { 格局, 争议标注 } = scan(锚点['假从财']());
    expect(格局!.名称).toBe('从财格');
    expect(格局!.真伪).toBe('假');
    expect(争议标注).toContain('从格不真（假从），喜忌按正格身弱论');
    expect(格局!.依据.join('')).toContain('余气微根');
  });

  it('F1 时辰未知：负断言不完整 → 降假从', () => {
    const b = 锚点['F1从财']();
    const { 格局 } = detectGeju(b.日主, 缺时柱(b.四柱));
    expect(格局!.类型).toBe('从格');
    expect(格局!.真伪).toBe('假');
    expect(格局!.依据.join('')).toContain('时辰未知');
  });

  it('弱水盘：戌中辛（中气生我）=有根 → 不从（根含生我中气，防满盘克泄耗误从）', () => {
    expect(scan(锚点['弱水身弱']()).格局).toBeNull();
  });

  it('有助不从：F1 时干改壬（比劫帮身）即破无助条件', () => {
    const 四柱 = 构造四柱([['丙', '寅'], ['甲', '午'], ['壬', '午'], ['壬', '子']]);
    expect(detectGeju('壬', 四柱).格局).toBeNull();
  });

  it('条件④负测（评审一轮补钉）：月支卯不参与 D火（本气乙/三合木/三会木皆离），无根无助等前序条件全成立仍不从', () => {
    // 丙寅 甲卯 壬午 丁未：D火全盘力量最高、壬无根（寅卯午未本中气无水金）、干无金水——唯月支卯与火无涉。
    const 四柱 = 构造四柱([['丙', '寅'], ['甲', '卯'], ['壬', '午'], ['丁', '未']]);
    expect(detectGeju('壬', 四柱).格局).toBeNull();
  });

  it('条件⑤负测（评审一轮补钉）：D火不透年/月/时干 → 不从；年干戊改丙（火透）即真从财（单字判别钉死⑤）', () => {
    expect(detectGeju('壬', 构造四柱([['戊', '午'], ['甲', '午'], ['壬', '午'], ['乙', '未']])).格局).toBeNull();
    const { 格局 } = detectGeju('壬', 构造四柱([['丙', '午'], ['甲', '午'], ['壬', '午'], ['乙', '未']]));
    expect(格局!.名称).toBe('从财格');
    expect(格局!.真伪).toBe('真');
  });

  it('从印/从强不在钉表：纯水盘力量最高为比劫类 → 判从直接 null（专旺另行接管）', () => {
    const b = 锚点['纯水身强']();
    // 直接喂专旺会命中，故先验证从格分支自身：以 detectGeju 结果反证为专旺而非从格
    const { 格局 } = scan(b);
    expect(格局!.类型).toBe('专旺');
  });
});

describe('专旺', () => {
  it('纯水四刃：润下真，喜[印,比劫,食伤]忌[官杀]财(火)中性+争议', () => {
    const { 格局, 争议标注 } = scan(锚点['纯水身强']());
    expect(格局!.类型).toBe('专旺');
    expect(格局!.名称).toBe('专旺格·润下');
    expect(格局!.真伪).toBe('真');
    expect(格局!.喜类别).toEqual(['印星', '比劫', '食伤']);
    expect(格局!.忌类别).toEqual(['官杀']);
    expect(格局!.中性类别).toEqual(['财星']);
    expect(争议标注.join('')).toContain('财星');
  });

  it('F2 乙木寅月卯日：曲直真', () => {
    const { 格局 } = scan(锚点['F2曲直']());
    expect(格局!.名称).toBe('专旺格·曲直');
    expect(格局!.真伪).toBe('真');
  });

  it('破格盘：申本气庚官杀破曲直 → 静默 null（无争议噪音，回正格）', () => {
    const { 格局, 争议标注 } = scan(锚点['破格曲直']());
    expect(格局).toBeNull();
    expect(争议标注).toEqual([]);
  });

  it('庚透干即破（F3 甲寅月两庚）：专旺 null 静默', () => {
    expect(scan(锚点['F3盘']()).格局).toBeNull();
  });

  it('F2 时辰未知：纯粹性负断言不完整 → 不判 + 争议标注', () => {
    const b = 锚点['F2曲直']();
    const { 格局, 争议标注 } = detectGeju(b.日主, 缺时柱(b.四柱));
    expect(格局).toBeNull();
    expect(争议标注.join('')).toContain('专旺格不判');
  });

  it('未得令不谈专旺（冬木水月木日）→ null 无痕', () => {
    const { 格局, 争议标注 } = scan(锚点['冬木']());
    expect(格局).toBeNull();
    expect(争议标注).toEqual([]);
  });
});

describe('入参防御', () => {
  it('未知日主天干 / 缺月柱 → 中文 Error', () => {
    const b = 锚点['冬木']();
    expect(() => detectGeju('癸', 构造四柱([['甲', '丑'], ['甲', '子'], ['甲', '寅'], ['甲', '子']]))).not.toThrow();
    expect(() => detectGeju('囗', b.四柱)).toThrow('未知日主天干');
    expect(() => detectGeju('甲', { 年: b.四柱.年, 月: null as never, 日: b.四柱.日, 时: b.四柱.时 })).toThrow('月柱');
  });
});

/**
 * 喜用神来源（契约 C2）纯函数单测：默认来源选择/解析五行来源/点选喜用神/点选忌神。
 * 契约：无盘→手动模式；自动带盘遇盘 null 回退手动值；喜用神至少 1（清空恢复全选）；
 * 喜忌互斥（点一侧自动从另一侧摘除）；全部纯函数不改入参（不可变）。
 *
 * ⚠️ 被测件是 .tsx：当前 vitest.config.ts 未配 jsx 覆盖（tsconfig jsx=preserve），
 * vite 对 tsx 做 import 分析会报错，故被测模块用运行时动态 import 探测——
 * 载得入就真测，载不入整组 skip（套件保持绿）。lead 在 vitest.config.ts 加
 * `oxc: { jsx: 'automatic' }` 一行后即恒真测（vitest 4 = rolldown-vite：esbuild 键会被
 * oxc 忽略，实测 esbuild.jsx 无效、oxc.jsx 14/14 绿；配置在他人名下，本文件不动它）。
 */
import { describe, expect, it } from 'vitest';
import type { WuXing, XiyongMingXiItem } from '@/lib/types';
import type { 五行选择 } from '@/components/xiyong-source';

type 被测模块 = {
  默认来源选择: (有盘: boolean) => { 模式: '自动带盘' | '手动勾选'; 手动: 五行选择 };
  解析五行来源: (
    盘: { 喜用神: WuXing[]; 忌神: WuXing[]; 明细?: XiyongMingXiItem[] } | null,
    选择: { 模式: '自动带盘' | '手动勾选'; 手动: 五行选择 },
  ) => 五行选择 & { 明细?: XiyongMingXiItem[] };
  点选喜用神: (现值: 五行选择, 行: WuXing) => 五行选择;
  点选忌神: (现值: 五行选择, 行: WuXing) => 五行选择;
};

/** 运行时探测载入（tsx 在缺少 jsx 覆盖配置的 harness 下解析失败 → undefined → 整组 skip）。 */
let 载: 被测模块 | undefined;
try {
  载 = (await import('@/components/xiyong-source')) as unknown as 被测模块;
} catch {
  载 = undefined;
}
const 测 = describe.skipIf(载 === undefined);

// 载不入时占位（skipIf 保证这些永不被调用）；显式标注 被测模块 防联合类型窄化丢 明细 返回
const 兜底: 被测模块 = {
  默认来源选择: () => ({ 模式: '手动勾选', 手动: { 喜用神: [], 忌神: [] } }),
  解析五行来源: () => ({ 喜用神: [], 忌神: [] }),
  点选喜用神: () => ({ 喜用神: [], 忌神: [] }),
  点选忌神: () => ({ 喜用神: [], 忌神: [] }),
};
const { 默认来源选择, 解析五行来源, 点选喜用神, 点选忌神 } = 载 ?? 兜底;

const 全集: readonly WuXing[] = ['木', '火', '土', '金', '水'];

测('默认来源选择', () => {
  it('有盘→自动带盘；无盘→手动勾选；手动值均为喜用全选、忌神空', () => {
    expect(默认来源选择(true)).toEqual({
      模式: '自动带盘',
      手动: { 喜用神: [...全集], 忌神: [] },
    });
    expect(默认来源选择(false)).toEqual({
      模式: '手动勾选',
      手动: { 喜用神: [...全集], 忌神: [] },
    });
  });
});

测('解析五行来源', () => {
  const 盘 = { 喜用神: ['水', '木'] as WuXing[], 忌神: ['火'] as WuXing[] };
  const 手动值 = 默认来源选择(false).手动;

  it('自动带盘 + 盘在场 → 取盘值（含明细透传）', () => {
    const 明细 = [{ 五行: '水' as WuXing, 十神关系: '印星' as const, 角色: '主用' as const }];
    const 结果 = 解析五行来源({ ...盘, 明细 }, 默认来源选择(true));
    expect(结果.喜用神).toEqual(['水', '木']);
    expect(结果.忌神).toEqual(['火']);
    expect(结果.明细).toEqual(明细);
  });

  it('自动带盘 + 盘 null → 回退手动值（不带明细）', () => {
    const 结果 = 解析五行来源(null, 默认来源选择(true));
    expect(结果).toEqual({ 喜用神: [...全集], 忌神: [] });
    expect(结果.明细).toBeUndefined();
  });

  it('手动勾选 → 无视盘取手动值', () => {
    const 结果 = 解析五行来源(盘, { 模式: '手动勾选', 手动: { 喜用神: ['土'], 忌神: ['木'] } });
    expect(结果).toEqual({ 喜用神: ['土'], 忌神: ['木'] });
  });

  it('不改入参（不可变）', () => {
    const 选择 = 默认来源选择(true);
    解析五行来源(盘, 选择);
    解析五行来源(null, 选择);
    expect(选择.手动.喜用神).toEqual([...全集]);
    expect(盘.喜用神).toEqual(['水', '木']);
    expect(手动值.忌神).toEqual([]);
  });
});

测('点选喜用神（至少 1 个 + 互斥）', () => {
  it('未选中 → 入喜用神并从忌神摘除', () => {
    const 现值: 五行选择 = { 喜用神: ['水'], 忌神: ['火', '土'] };
    expect(点选喜用神(现值, '火')).toEqual({ 喜用神: ['水', '火'], 忌神: ['土'] });
  });

  it('已选中 → 摘除', () => {
    const 现值: 五行选择 = { 喜用神: ['水', '木'], 忌神: [] };
    expect(点选喜用神(现值, '水')).toEqual({ 喜用神: ['木'], 忌神: [] });
  });

  it('摘空 → 恢复全选（剔除仍在忌神者以维互斥）', () => {
    const 现值: 五行选择 = { 喜用神: ['水'], 忌神: ['土'] };
    const 结果 = 点选喜用神(现值, '水');
    expect(结果.喜用神).toEqual(['木', '火', '金', '水']);
    expect(结果.忌神).toEqual(['土']);
    expect(结果.喜用神).toHaveLength(4); // 至少 1 且与忌互斥
  });

  it('不改入参', () => {
    const 现值: 五行选择 = { 喜用神: ['水'], 忌神: ['火'] };
    点选喜用神(现值, '火');
    点选喜用神(现值, '水');
    expect(现值).toEqual({ 喜用神: ['水'], 忌神: ['火'] });
  });
});

测('点选忌神（可选 + 互斥 + 喜用保底）', () => {
  it('未选中 → 入忌神并从喜用神摘除', () => {
    const 现值: 五行选择 = { 喜用神: ['水', '火'], 忌神: [] };
    expect(点选忌神(现值, '火')).toEqual({ 喜用神: ['水'], 忌神: ['火'] });
  });

  it('已选中 → 摘除（忌神可空）', () => {
    const 现值: 五行选择 = { 喜用神: ['水'], 忌神: ['火'] };
    expect(点选忌神(现值, '火')).toEqual({ 喜用神: ['水'], 忌神: [] });
  });

  it('摘后喜用为空 → 以「全集−新忌」兜底，喜用不跌破 1 个', () => {
    const 现值: 五行选择 = { 喜用神: ['水'], 忌神: ['火', '土'] };
    const 结果 = 点选忌神(现值, '水');
    expect(结果.喜用神).toEqual(['木', '金']);
    expect(结果.忌神).toEqual(['火', '土', '水']);
  });

  it('忌神将占满五行 → 该次点选不生效（原样返回）', () => {
    const 现值: 五行选择 = { 喜用神: ['水'], 忌神: ['木', '火', '土', '金'] };
    expect(点选忌神(现值, '水')).toBe(现值);
  });

  it('不改入参', () => {
    const 现值: 五行选择 = { 喜用神: ['水'], 忌神: ['火'] };
    点选忌神(现值, '木');
    点选忌神(现值, '火');
    expect(现值).toEqual({ 喜用神: ['水'], 忌神: ['火'] });
  });
});

/**
 * score.ts 测试：三盘手工预算全链路（走真实 kangxi / shuli-81 / sancai 表，不手搭 GeItem）
 * + 基础分表/权重常量对账 + 档位边界 + 值域不变量 + 越表值防御抛错。
 *
 * 口径（主 agent 定稿）：五格 大吉95/吉85/半吉70/凶30；三才 大吉95/吉85/半吉65/凶35/大凶15；
 * 权重 人格30/地格20/总格20/外格10/三才20/天格0（祖传豁免只展示不计分）；
 * 综合分 = Math.round(Σ 权重×基础分 / 100)，值域 [27,95]，满分 95 不可达 100。
 */
import { describe, it, expect } from 'vitest';

import { computeWuge } from '@/lib/wuge/geju';
import { GE_BASE, SANCAI_BASE, WUGE_WEIGHTS, scoreWuge, tierOf } from '@/lib/wuge/score';
import type { GeItem, WugeResult } from '@/lib/types';

type 计分项 = Pick<WugeResult, '人格' | '地格' | '总格' | '外格' | '三才'>;

/** 合成五格：仅用于单测映射表/边界/防御分支，不查表、无笔画语义（三盘预算不走这里）。 */
const ge = (吉凶: GeItem['吉凶']): GeItem => ({ 数理: 1, 康熙笔画和: 1, 吉凶, 含义: '占位' });
const 合成 = (
  人格: GeItem['吉凶'],
  地格: GeItem['吉凶'],
  总格: GeItem['吉凶'],
  外格: GeItem['吉凶'],
  三才吉凶: string,
): 计分项 => ({
  人格: ge(人格),
  地格: ge(地格),
  总格: ge(总格),
  外格: ge(外格),
  三才: { 配置: '土木火', 吉凶: 三才吉凶, 含义: '占位' },
});

describe('三盘手工预算（computeWuge 全链路）', () => {
  it('王浩然(4,11,12)：人15大吉/地23大吉/外13大吉/总27半吉/三才土土火大吉 → 90 上乘', () => {
    // 0.30×95 + 0.20×95 + 0.20×70(总) + 0.10×95(外) + 0.20×95(三才)
    // = 28.5 + 19 + 14 + 9.5 + 19 = 90；天格5大吉若被误计会得 91——本断言防错。
    const r = computeWuge('王', '浩然');
    expect(r).not.toBeNull();
    expect(r!.评分).toEqual({ 综合分: 90, 档位: '上乘' });
  });

  it('李鑫(7,24 单姓单名)：人31大吉/地25吉/外2凶(恒2边界)/总31大吉/三才金木土凶 → 74.5→75 中上', () => {
    // 0.30×95 + 0.20×85 + 0.20×95(总) + 0.10×30(外恒2，照常扣分不豁免) + 0.20×35(三才)
    // = 28.5 + 17 + 19 + 3 + 7 = 74.5 → Math.round → 75
    const r = computeWuge('李', '鑫');
    expect(r!.外格).toMatchObject({ 数理: 2, 吉凶: '凶' });
    expect(r!.评分).toEqual({ 综合分: 75, 档位: '中上' });
  });

  it('马鑫龘(10,24,48)：人34凶/地72凶/外49半吉/总82归约2凶/三才木火木大吉 → 47 欠佳', () => {
    // 0.30×30 + 0.20×30 + 0.20×30(总 82-80=2) + 0.10×70(外49) + 0.20×95(三才)
    // = 9 + 6 + 6 + 7 + 19 = 47
    const r = computeWuge('马', '鑫龘');
    expect(r!.总格).toMatchObject({ 数理: 2, 吉凶: '凶' });
    expect(r!.评分).toEqual({ 综合分: 47, 档位: '欠佳' });
  });
});

describe('基础分表与权重常量', () => {
  it('五格基础分：大吉95/吉85/半吉70/凶30', () => {
    expect(GE_BASE).toEqual({ 大吉: 95, 吉: 85, 半吉: 70, 凶: 30 });
  });

  it('三才基础分（五档含大凶）：大吉95/吉85/半吉65/凶35/大凶15', () => {
    expect(SANCAI_BASE).toEqual({ 大吉: 95, 吉: 85, 半吉: 65, 凶: 35, 大凶: 15 });
  });

  it('权重合计 100%，天格豁免为 0', () => {
    expect(WUGE_WEIGHTS).toEqual({ 人格: 30, 地格: 20, 总格: 20, 外格: 10, 三才: 20, 天格: 0 });
    expect(Object.values(WUGE_WEIGHTS).reduce((a, b) => a + b, 0)).toBe(100);
  });
});

describe('加权公式与值域不变量', () => {
  it('全大吉+三才大吉 = 95：满分 95，不可达 100（值域上界钉死）', () => {
    expect(scoreWuge(合成('大吉', '大吉', '大吉', '大吉', '大吉')))
      .toEqual({ 综合分: 95, 档位: '上乘' });
  });

  it('全凶+三才大凶 = 27：值域下界钉死', () => {
    // 0.8×30 + 0.2×15 = 24 + 3 = 27
    expect(scoreWuge(合成('凶', '凶', '凶', '凶', '大凶')))
      .toEqual({ 综合分: 27, 档位: '欠佳' });
  });

  it('人格权重最重：同一档替换人格对总分影响最大', () => {
    // 基线全凶/三才大凶=27；把人格提到大吉：+0.30×(95−30)=+19.5 → 46.5 → 47
    expect(scoreWuge(合成('大吉', '凶', '凶', '凶', '大凶'))).toEqual({ 综合分: 47, 档位: '欠佳' });
    // 把外格提到大吉仅 +0.10×65=+6.5 → 33.5 → 34
    expect(scoreWuge(合成('凶', '凶', '凶', '大吉', '大凶'))).toEqual({ 综合分: 34, 档位: '欠佳' });
  });
});

describe('档位边界（≥90 上乘 / 80~89 优良 / 70~79 中上 / 60~69 及格 / <60 欠佳）', () => {
  it.each([
    [95, '上乘'], [90, '上乘'],
    [89, '优良'], [80, '优良'],
    [79, '中上'], [70, '中上'],
    [69, '及格'], [60, '及格'],
    [59, '欠佳'], [27, '欠佳'],
  ] as const)('%d → %s', (分, 档位) => {
    expect(tierOf(分)).toBe(档位);
  });
});

describe('越表值防御（类型枚举内四档外无他值，运行时抛中文 Error）', () => {
  it('五格吉凶出现「末定」类越表值 → 抛错', () => {
    expect(() => scoreWuge(合成('末定', '吉', '吉', '吉', '吉'))).toThrow(/末定/);
  });

  it('三才吉凶查不到评分档 → 抛中文 Error', () => {
    expect(() => scoreWuge(合成('吉', '吉', '吉', '吉', '半凶'))).toThrow(/三才/);
  });
});

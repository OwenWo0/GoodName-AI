/** 把时柱抹掉（时辰未知降级：四柱.时=null）。 */
export function 缺时柱(四柱: BaziResult['四柱']): BaziResult['四柱'] {
  return { 年: 四柱.年, 月: 四柱.月, 日: 四柱.日, 时: null };
}

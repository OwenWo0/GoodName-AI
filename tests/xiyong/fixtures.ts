/**
 * tests/xiyong 共享夹具：手工构造四柱（不依赖 lunar-typescript）。
 *
 * 四柱格式：[年, 月, 日, 时]，各为 [天干, 地支]。
 * 十神由 lib 推导，夹具不手写，避免十神表错误污染断言。
 * 期望分值为净分制（喜用神算法修复 C.2），实算复核见 tests/xiyong/wangshuai.test.ts。
 */
import type { BaziResult, Zhu } from '../../src/lib/types';

/** 由 [干,支] 对列表构造 四柱 对象（按传入顺序命名为 年/月/日/时）。 */
export function 构造四柱(
  pillars: Array<readonly [string, string]>
): BaziResult['四柱'] {
  const names = ['年', '月', '日', '时'] as const;
  const out = {} as BaziResult['四柱'];
  pillars.forEach(([干, 支], i) => {
    (out as Record<string, Zhu>)[names[i]] = {
      天干: 干,
      地支: 支,
      干支: `${干}${支}`,
      藏干: [],
      十神: [],
      纳音: '',
    };
  });
  return out;
}

/** 构造最小 BaziResult（xiyong 只消费 四柱/日主，其余字段给占位值）。 */
export function 构造八字(
  pillars: Array<readonly [string, string]>,
  日主: string
): BaziResult {
  return {
    四柱: 构造四柱(pillars),
    日主,
    五行力量: [],
    五行缺失: [],
    大运: [],
    真太阳时: {
      输入北京时间: '2000-01-01 00:00:00',
      校正分钟: 0,
      校正后本地时间: '2000-01-01 00:00:00',
      地点经度: 116.4,
    },
    晚子时流派: '不涉及',
  };
}

